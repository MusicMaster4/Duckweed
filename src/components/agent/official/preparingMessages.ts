const pickPreparingMessage = createCooldownPicker(
  PREPARING_MESSAGES,
  PREPARING_MESSAGES[0]!,
  Math.random,
  {
    poolId: "preparing-messages",
    keyOf: (message) => message,
    cooldownFraction: 0.5,
  },
);

/** Shared across panes. Half-pool cooldown, not a fresh lottery each time. */
export function nextPreparingMessage(): string {
  return pickPreparingMessage();
}

/** Enough for any plausible number of live thinking clusters. */
const REGISTRY_LIMIT = 128;

/**
 * Preparing labels remount with their thinking row on tab switch / pane split.
 * Hold the pick by cluster id so the same wait keeps the same stand-in line.
 */
const messageAssignments = new Map<string, string>();

function rememberAssignment<T>(store: Map<string, T>, clusterId: string, value: T): T {
  if (store.size >= REGISTRY_LIMIT) {
    const oldest = store.keys().next().value;
    if (oldest !== undefined) store.delete(oldest);
  }
  store.set(clusterId, value);
  return value;
}

/** Same preparing line for the same cluster across remounts. */
export function preparingMessageFor(clusterId: string): string {
  const existing = messageAssignments.get(clusterId);
  if (existing) return existing;
  return rememberAssignment(messageAssignments, clusterId, nextPreparingMessage());
}

/** Chance that a live Thinking headline uses a stand-in line instead. */
export const FUNNY_THINKING_LABEL_CHANCE = 0.01;

const funnyLabelAssignments = new Map<string, boolean>();
let funnyLabelRandom = Math.random;

/** Test-only: pin the 1% Thinking-label roll. */
export function setFunnyThinkingLabelRandomForTests(random: () => number): void {
  funnyLabelRandom = random;
}

/** Test-only: drop per-cluster stand-in and headline rolls. */
export function resetPreparingMessageAssignmentsForTests(): void {
  messageAssignments.clear();
  funnyLabelAssignments.clear();
  funnyLabelRandom = Math.random;
}

function funnyThinkingLabelEnabled(clusterId: string): boolean {
  const existing = funnyLabelAssignments.get(clusterId);
  if (existing !== undefined) return existing;
  return rememberAssignment(
    funnyLabelAssignments,
    clusterId,
    funnyLabelRandom() < FUNNY_THINKING_LABEL_CHANCE,
  );
}

/**
 * Headline for a live thinking row. Empty waits keep the default "Thinking"
 * label (the stand-in line still sits in the shimmer). While a trace is on
 * screen and the model is still working, a small chance swaps the label for
 * a pool line, using the same half-pool cooldown as the empty-wait case.
 */
export function thinkingHeadlineFor(
  clusterId: string,
  options: { working: boolean; hasLatest: boolean },
): string {
  if (!options.working || !options.hasLatest) return "Thinking";
  if (!funnyThinkingLabelEnabled(clusterId)) return "Thinking";
  return preparingMessageFor(clusterId);
}
