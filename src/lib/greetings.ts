/**
 * Pick from a phrase list with a 70% pool cooldown.
 *
 * Pure random repeats the same joke too often. Instead, once a line is chosen it
 * is blocked until 70% of the list has been drawn (floor(n * 0.7) later picks).
 * With 10 phrases that is a 7-round sit-out; available pool stays at least ~30%.
 * State is module-level so new panes share the same anti-repeat history, and the
 * recent keys ride durable storage so an app update does not reset the sit-outs.
 */
function createCooldownPicker(phrases: readonly string[], poolId: string): () => string {
  return createPoolCooldownPicker(phrases, "", Math.random, {
    poolId,
    // Content keys survive list reorders; a removed joke simply drops out.
    keyOf: (phrase) => phrase,
  });
}

const pickGreeting = createCooldownPicker(GREETINGS, "greetings");
const pickUnclaimed = createCooldownPicker(UNCLAIMED, "unclaimed");

/** One greeting, random among phrases not on 70% pool cooldown. */
export function randomGreeting(): string {
  return pickGreeting();
}

/** One unclaimed-tab line, random among phrases not on 70% pool cooldown. */
export function randomUnclaimedGreeting(): string {
  return pickUnclaimed();
}

/**
 * Greetings are keyed by terminal id, not by React mount.
 *
 * Splitting a pane restructures the tree and remounts the original leaf under a
 * SplitView. If the line lived only in useMemo([]), that remount would pick a
 * new phrase while you were still looking at it. Cache here so the same shell
 * keeps the same line for its whole life.
 */
const greetingByTerm = new Map<string, string>();
const unclaimedByTerm = new Map<string, string>();

/** Stable empty-pane line for this terminal. Picked once, reused on remount. */
export function greetingFor(termId: string): string {
  let line = greetingByTerm.get(termId);
  if (line === undefined) {
    line = randomGreeting();
    greetingByTerm.set(termId, line);
  }
  return line;
}

/** Stable unclaimed-tab line for this terminal. */
export function unclaimedGreetingFor(termId: string): string {
  let line = unclaimedByTerm.get(termId);
  if (line === undefined) {
    line = randomUnclaimedGreeting();
    unclaimedByTerm.set(termId, line);
  }
  return line;
}

/** Drop cached lines when the terminal goes away. */
export function clearGreetings(termId: string): void {
  greetingByTerm.delete(termId);
  unclaimedByTerm.delete(termId);
}
